from syncode import Syncode


grammar = r"""
start: "Operand1: " NUMBER "\nOperand2: " NUMBER "\nOperator: " OP
NUMBER: /-?[0-9]+(\.[0-9]*)?/
OP: "+" | "-" | "*" | "/"
"""
few_shot = """Extract the two numbers and the operator from each query.

Query: What is 12.5 plus 3.5?
Operand1: 12.5
Operand2: 3.5
Operator: +

Query: What is 90.0 minus 15.25?
Operand1: 90.0
Operand2: 15.25
Operator: -

Query: What is 8. times 2.5?
Operand1: 8.
Operand2: 2.5
Operator: *

Query: What is 99.9 divided by 3.0?
Operand1: 99.9
Operand2: 3.0
Operator: /

"""
syn_llm = Syncode(
    model="microsoft/phi-2",
    mode="grammar_strict",
    grammar=grammar,
    parse_output_only=True,
    max_new_tokens=40,
)


def run_syncode(textual_query):
    prompt = few_shot + "Query: " + textual_query + "\n"
    output = syn_llm.infer(prompt)[0]
    output = output.strip()

    lines = output.split("\n")
    operand1_text = ""
    operand2_text = ""
    operator = ""

    for line in lines:
        line = line.strip()
        if line.startswith("Operand1:"):
            operand1_text = line.split(":", 1)[1].strip()
        elif line.startswith("Operand2:"):
            operand2_text = line.split(":", 1)[1].strip()
        elif line.startswith("Operator:"):
            operator = line.split(":", 1)[1].strip()

    operand1 = float(operand1_text)
    operand2 = float(operand2_text)


    if operator == "+":
        answer = operand1 + operand2
    elif operator == "-":
        answer = operand1 - operand2
    elif operator == "*":
        answer = operand1 * operand2
    elif operator == "/":
        answer = operand1 / operand2
    else:
        raise ValueError("Unknown operator: " + operator)

    return ([operand1, operand2], operator, float(answer))

print(run_syncode("What is 327. multiplied by 11.0?"))
print(run_syncode("What is 45.1 plus 23.54?"))
print(run_syncode("What is 120.4 divided by 4.0?"))

print(run_syncode("What is 7.0 minus 2.5?"))
